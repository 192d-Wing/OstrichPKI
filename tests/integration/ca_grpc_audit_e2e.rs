// ---------------------------------------------------------------- test PKI ---
// rcgen gRPC PKI (same shape as grpc_mtls_e2e.rs).

struct Pki {
    ca: CertifiedIssuer<'static, KeyPair>,
}

struct Leaf {
    cert_pem: String,
    key_pem: String,
}

impl Pki {
    fn new(cn: &str) -> Self {
        let mut p = CertificateParams::new(Vec::<String>::new()).expect("ca params");
        p.distinguished_name = DistinguishedName::new();
        p.distinguished_name.push(DnType::CommonName, cn);
        p.is_ca = IsCa::Ca(BasicConstraints::Unconstrained);
        p.key_usages = vec![KeyUsagePurpose::KeyCertSign, KeyUsagePurpose::CrlSign];
        let key = KeyPair::generate_for(&rcgen::PKCS_ECDSA_P256_SHA256).expect("ca key");
        Self {
            ca: CertifiedIssuer::self_signed(p, key).expect("ca cert"),
        }
    }

    fn leaf(&self, cn: &str, sans: &[&str], eku: ExtendedKeyUsagePurpose) -> Leaf {
        let sans: Vec<String> = sans.iter().map(|s| s.to_string()).collect();
        let mut p = CertificateParams::new(sans).expect("leaf params");
        p.distinguished_name = DistinguishedName::new();
        p.distinguished_name.push(DnType::CommonName, cn);
        p.extended_key_usages = vec![eku];
        // RFC 5280 §4.2.1.1: AKI (admin leaves are matched to the anchor by
        // AKI, SEC-201).
        p.use_authority_key_identifier_extension = true;
        let key = KeyPair::generate().expect("leaf key");
        let cert = p.signed_by(&key, &self.ca).expect("leaf cert");
        Leaf {
            cert_pem: cert.pem(),
            key_pem: key.serialize_pem(),
        }
    }

    fn client(&self, cn: &str) -> Leaf {
        self.leaf(cn, &[cn], ExtendedKeyUsagePurpose::ClientAuth)
    }

    fn ca_pem(&self) -> String {
        self.ca.pem()
    }
}

/// Private temporary directory for the TLS PEM files: random name, created
/// exclusively with mode 0700 (Unix), files created exclusively with mode
/// 0600, removed on drop (also when an assertion panics). No `tempfile`
/// dependency (std only).
///
/// NIST 800-53: SI-12 (test code) - the test TLS private key is not left
/// readable by other local users or behind after the run.
struct PrivateTempDir {
    path: PathBuf,
}

impl PrivateTempDir {
    fn new() -> Self {
        let path = std::env::temp_dir().join(format!(
            "ostrich-grpc-audit-e2e-{}",
            uuid::Uuid::new_v4().simple()
        ));
        let mut builder = std::fs::DirBuilder::new();
        #[cfg(unix)]
        {
            use std::os::unix::fs::DirBuilderExt;
            builder.mode(0o700);
        }
        // Not recursive: fails if the path already exists.
        builder.create(&path).expect("create private temp dir");
        Self { path }
    }

    fn file(&self, tag: &str, contents: &str) -> PathBuf {
        use std::io::Write;
        let path = self.path.join(format!("{tag}.pem"));
        let mut options = std::fs::OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        options
            .open(&path)
            .and_then(|mut f| f.write_all(contents.as_bytes()))
            .expect("write temp pem");
        path
    }
}

impl Drop for PrivateTempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

/// Hex serial of a PEM certificate, in the `AuthorizedGrpcPeer::serial_hex`
/// form (DER INTEGER content octets, sign byte included).
fn serial_hex(cert_pem: &str) -> String {
    use der::Decode;
    let der = CertificateDer::from_pem_slice(cert_pem.as_bytes()).expect("leaf pem");
    let cert = x509_cert::Certificate::from_der(der.as_ref()).expect("leaf der");
    hex::encode(cert.tbs_certificate.serial_number.as_bytes())
}

/// Assemble a DER Certificate from its TBS and signature (mirrors ostrich-init).
fn assemble_certificate(tbs_der: &[u8], signature: &[u8]) -> Vec<u8> {
    use der::{asn1::BitString, Decode, Encode};
    use x509_cert::{Certificate as X509Cert, TbsCertificate};
    let tbs = TbsCertificate::from_der(tbs_der).expect("re-parse TBS");
    let signature_algorithm = tbs.signature.clone();
    let signature = BitString::from_bytes(signature).expect("signature BitString");
    X509Cert {
        tbs_certificate: tbs,
        signature_algorithm,
        signature,
    }
    .to_der()
    .expect("encode certificate")
}

