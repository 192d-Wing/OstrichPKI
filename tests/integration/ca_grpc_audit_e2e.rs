//! Live e2e (Postgres + SoftHSM): the REAL `CaGrpcService` behind the real
//! mTLS listener (`bind_mtls_incoming`) and `SubjectAllowlistLayer` with the
//! production `CA_GRPC_METHOD_RULES`, called with the real `CaGrpcClient`.
//! Asserts the STORED, signed audit records of IssueCertificate,
//! RevokeCertificate and GenerateCrl attribute the verified mTLS peer:
//! `actor` = peer subject DN and `details.authenticated_caller{,_issuer,_serial}`
//! = the peer certificate's subject, issuer and serial. The whole stored chain
//! (including those gRPC-written records) then verifies against the CA
//! certificate's SPKI (`verify_signed_chain`), and a corrupted signature on
//! the gRPC `crl_generation` record is detected.
//!
//! The listener and layer get the same denial audit hook as ca-server's
//! `start_grpc_listener` (`AuthAuditAdapter` over an unsigned
//! `DatabaseAuditSink`, the `grpc_audit` sink), so the Issuer -> GenerateCrl
//! denial is asserted as a stored `access_denied` Failure record whose actor
//! is the denied peer. `start_grpc_listener` itself is private to the
//! ca-server binary; this test mirrors its assembly rather than calling it.
//!
//! This is the handler-glue evidence the offline `grpc_mtls_e2e` stub cannot
//! give: a mutant that drops the verified caller in a handler (e.g. M13h,
//! `crl_actor(caller.as_ref())` -> `crl_actor(None)` in `generate_crl`, which
//! records actor `unauthenticated` with no `authenticated_caller*` keys) fails
//! here. It also proves an Issuer identity cannot reach GenerateCrl through
//! the real stack (no `crl_generation` record is created).
//!
//! Gated on DATABASE_URL + PKCS11_MODULE_PATH + PKCS11_SLOT + PKCS11_PIN; skips
//! otherwise, and FAILS instead with `OSTRICH_REQUIRE_LIVE_TESTS=1` (CI). The
//! database name must have a `test` token. Run with `--test-threads=1` (one
//! PKCS#11 provider, shared database). TLS key material is written to a
//! private (0700) temporary directory, key files 0600, removed on drop.
//!
//! COMPLIANCE MAPPING (test evidence):
//! - NIST 800-53: AU-3 (who: verified peer), AU-10 (gRPC-written records
//!   signed by the CA key and verified against its SPKI), AU-12 (generated by
//!   the gRPC handlers and the listener layer), AU-2 / AC-3 (denial audited),
//!   IA-3 (mTLS device identity, positive path), AC-3 / AC-6 (Admin-only
//!   GenerateCrl), SA-11, CA-2
//! - NIAP PP-CA: FAU_GEN.1, FAU_GEN.2 (user identity association),
//!   FDP_ACF.1, FTP_ITC.1, FCS_COP.1 (audit signature verification)
//! - RFC 5280 §4.1.2.2 / §4.1.2.4 - the peer certificate's serial and issuer
//!   are recorded

