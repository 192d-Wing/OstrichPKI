/// HSM-backed (SoftHSM) ECDSA P-256 CA with a self-signed root, registered
/// in the database (mirrors the ostrich-ca e2e modules). Approval is off
/// (automated issuance); proof-of-possession stays at its secure default.
/// Returns the CA, the profile name and the CA public key (SPKI DER) for
/// `verify_signed_chain`.
async fn build_ca(pool: &DatabasePool, env: &LiveEnv) -> (CertificateAuthority, String, Vec<u8>) {
    let crypto: Box<dyn CryptoProvider> =
        CryptoProviderFactory::create_pkcs11_provider(Path::new(&env.module), env.slot, &env.pin)
            .await
            .expect("PKCS#11 provider");
    let key_handle = crypto
        .generate_key_pair(KeyType::EcP256, KEY_LABEL, false)
        .await
        .expect("generate CA key in HSM");
    let ca_spki = crypto
        .export_public_key(&key_handle)
        .await
        .expect("export CA public key");
    let sig_alg = Algorithm::EcdsaP256Sha256;

    let subject = Dn {
        common_name: Some("OstrichPKI gRPC Audit E2E Root CA".to_string()),
        organization: Some("OstrichPKI".to_string()),
        ..Default::default()
    };
    let mut serial_bytes = ostrich_common::util::random::secure_random_bytes(20);
    serial_bytes[0] &= 0x7F; // RFC 5280 §4.1.2.2 positive serial
    let serial = SerialNumber::from_bytes(serial_bytes).expect("serial");
    let tbs = CertificateBuilder::new()
        .serial_number(serial.clone())
        .subject(subject.clone())
        .issuer(subject.clone())
        .validity_days(3650)
        .public_key(ca_spki.clone())
        .basic_constraints(true, None)
        .add_key_usage(KeyUsage::KeyCertSign)
        .add_key_usage(KeyUsage::CrlSign)
        .add_key_usage(KeyUsage::DigitalSignature)
        .signature_algorithm(sig_alg)
        .build_tbs()
        .expect("build TBS");
    let (not_before, not_after) = (tbs.not_before, tbs.not_after);
    let tbs_der = tbs.to_der().expect("encode TBS");
    let raw_sig = crypto
        .sign(&key_handle, sig_alg, &tbs_der)
        .await
        .expect("sign root TBS");
    let x509_sig =
        ostrich_x509::signing::encode_x509_signature(sig_alg, raw_sig).expect("x509 signature");
    let ca_der = assemble_certificate(&tbs_der, &x509_sig);
    let ca_pem = pem_rfc7468::encode_string("CERTIFICATE", pem_rfc7468::LineEnding::LF, &ca_der)
        .expect("ca pem");
    let dn = subject.to_string_rfc4514();

    let ca_repo = CaRepository::new(pool.clone());
    let ca_key_row = ca_repo
        .create_ca_key(
            KEY_LABEL,
            "EcP256",
            "EcdsaP256Sha256",
            "Pkcs11",
            Some(env.slot as i64),
            &key_handle.key_id,
            false,
        )
        .await
        .expect("register CA key");
    let ca_cert_row = ca_repo
        .create_ca_certificate(
            ca_key_row.id,
            serial.as_bytes(),
            &dn,
            &dn,
            not_before,
            not_after,
            &ca_der,
            &ca_pem,
            true,
            None,
            None,
        )
        .await
        .expect("register CA certificate");

    let now = chrono::Utc::now();
    let ca_model = Certificate {
        id: ca_cert_row.id,
        ca_id: ca_cert_row.id,
        serial_number: serial.as_bytes().to_vec(),
        subject_dn: dn.clone(),
        issuer_dn: dn,
        not_before,
        not_after,
        der_encoded: ca_der,
        pem_encoded: ca_pem,
        revoked: false,
        revocation_time: None,
        revocation_reason: None,
        issuer_service: Some("CA".to_string()),
        requestor: None,
        profile_name: None,
        metadata: None,
        request_id: None,
        created_at: now,
        updated_at: now,
    };
    let mut ca = CertificateAuthority::new(ca_model, key_handle, crypto, pool.clone(), 24)
        .expect("CertificateAuthority::new");
    ca.set_approval_config(ApprovalConfig {
        require_approval: false,
        ..ApprovalConfig::default()
    });
    let profile = CertificateProfile::tls_server(397);
    let profile_name = profile.name.clone();
    ca.add_profile(profile);
    (ca, profile_name, ca_spki)
}

/// Audit events of `event_type` with `outcome = success`.
fn successes<'a>(events: &'a [AuditEvent], event_type: &str) -> Vec<&'a AuditEvent> {
    events
        .iter()
        .filter(|e| e.event_type == event_type && e.outcome == "success")
        .collect()
}

/// The record attributes the verified peer `subject` (with the certificate's
/// issuer and serial) and is signed by the CA key (AU-3, AU-10, FAU_GEN.2).
/// `what` is a static label; failure messages never echo stored or
/// certificate-derived values (`assert!`, not `assert_eq!`).
fn assert_peer_attributed(event: &AuditEvent, what: &str, subject: &str, serial: &str) {
    assert!(event.actor == subject, "{what}: actor is the verified peer");
    let details = event
        .details
        .as_ref()
        .unwrap_or_else(|| panic!("{what}: details present"));
    assert!(
        details["authenticated_caller"] == subject,
        "{what}: authenticated_caller is the peer subject"
    );
    assert!(
        details["authenticated_caller_issuer"] == format!("CN={CLIENT_CA_CN}"),
        "{what}: authenticated_caller_issuer is the client CA"
    );
    assert!(
        details["authenticated_caller_serial"] == serial,
        "{what}: authenticated_caller_serial is the peer serial"
    );
    assert!(
        event.signature.is_some(),
        "{what}: record is signed (AU-10)"
    );
    assert!(
        event.signing_key_id.as_deref() == Some(KEY_LABEL),
        "{what}: signing_key_id names the CA key"
    );
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn grpc_handlers_record_verified_peer_as_audit_actor() {
    let Some(env) = live_env(TEST, false) else {
        return;
    };

    let pool = DatabasePool::new(&PoolConfig::from_url(&env.db_url).expect("DATABASE_URL"))
        .await
        .expect("connect to test DB");
    // Test-safety guard: never DELETE from a non-test database.
    assert_disposable_db(&pool, TEST).await;
    clear_tables(&pool).await;

    let (ca, profile_name, ca_spki) = build_ca(&pool, &env).await;
    let tmp = PrivateTempDir::new();

    // --- gRPC mTLS PKI and the production listener stack ---
    let server_pki = Pki::new("Audit E2E gRPC Server CA");
    let client_pki = Pki::new(CLIENT_CA_CN);
    let server_leaf = server_pki.leaf(
        "ca-service",
        &["localhost", "127.0.0.1"],
        ExtendedKeyUsagePurpose::ServerAuth,
    );
    let acme_leaf = client_pki.client("acme-server");
    let admin_leaf = client_pki.client("ops-admin");
    let settings = TlsSettings {
        cert_path: tmp.file("srv-cert", &server_leaf.cert_pem),
        key_path: tmp.file("srv-key", &server_leaf.key_pem),
        client_ca_path: Some(tmp.file("cli-ca", &client_pki.ca_pem())),
        optional_client_auth: false,
    };
    let server_config = grpc_server_config(&settings).expect("server config");
    // Same denial / handshake-failure audit wiring as ca-server
    // `start_grpc_listener`: AuthAuditAdapter over the unsigned DB sink
    // (`grpc_audit`), shared by the listener and the layer (AU-2, AU-12).
    let grpc_audit: Arc<dyn AuditSink> = Arc::new(DatabaseAuditSink::new(pool.clone()));
    let hook: Arc<dyn AuthAuditHook> = Arc::new(AuthAuditAdapter::new(grpc_audit));
    let incoming = bind_mtls_incoming(
        "127.0.0.1:0".parse().expect("addr"),
        server_config,
        Some(hook.clone()),
        LISTENER,
    )
    .await
    .expect("bind");
    let port = incoming.local_addr().port();

    let registry = Arc::new(
        GrpcClientRegistry::parse(
            &[ACME_SUBJECT.to_string()],
            &[],
            &[ADMIN_SUBJECT.to_string()],
        )
        .expect("registry"),
    );
    let anchor = CertificateDer::from_pem_slice(client_pki.ca_pem().as_bytes()).expect("anchor");
    let layer =
        SubjectAllowlistLayer::new(registry.clone(), CA_GRPC_METHOD_RULES, Some(hook), LISTENER)
            .with_client_trust_anchors(&[anchor])
            .expect("client trust anchors");
    let policy = IssuerProfilePolicy::parse(
        std::slice::from_ref(&profile_name),
        &[],
        Some(&registry),
        &[CertificateProfile::tls_server(397)],
    )
    .expect("profile policy");
    let service = CaGrpcService::new(Arc::new(ca), Arc::new(policy));
    assert!(
        service.requires_peer(),
        "mTLS service refuses peerless calls"
    );
    tokio::spawn(async move {
        tonic::transport::Server::builder()
            .layer(layer)
            .add_service(CertificateAuthorityServiceServer::new(service))
            .serve_with_incoming_shutdown(incoming, std::future::pending::<()>())
            .await
            .expect("serve");
    });

    let client_config = |leaf: &Leaf| GrpcClientConfig {
        endpoint: format!("https://127.0.0.1:{port}"),
        client_cert_pem: leaf.cert_pem.clone(),
        client_key_pem: zeroize::Zeroizing::new(leaf.key_pem.clone()),
        ca_cert_pem: server_pki.ca_pem(),
        server_name: Some("localhost".to_string()),
        max_retries: 1,
        ..Default::default()
    };
    let acme = CaGrpcClient::new(client_config(&acme_leaf))
        .await
        .expect("acme mTLS connect");
    let admin = CaGrpcClient::new(client_config(&admin_leaf))
        .await
        .expect("admin mTLS connect");
    let mut acme_rpc = CertificateAuthorityServiceClient::new(acme.channel());
    let mut admin_rpc = CertificateAuthorityServiceClient::new(admin.channel());

    // --- Issue (Issuer identity) with a CSR (proof-of-possession) ---
    let leaf_name = "grpc-audit-e2e.example";
    let leaf_key = KeyPair::generate().expect("leaf key");
    let mut csr_params = CertificateParams::new(vec![leaf_name.to_string()]).expect("csr params");
    csr_params.distinguished_name = DistinguishedName::new();
    csr_params
        .distinguished_name
        .push(DnType::CommonName, leaf_name);
    let csr_der = csr_params
        .serialize_request(&leaf_key)
        .expect("csr")
        .der()
        .to_vec();
    let public_key = ostrich_x509::parser::parse_csr(&csr_der)
        .expect("parse csr")
        .public_key;
    let issued = acme_rpc
        .issue_certificate(Request::new(IssueCertificateRequest {
            profile_name: profile_name.clone(),
            subject: Some(ProtoDn {
                common_name: Some(leaf_name.to_string()),
                ..Default::default()
            }),
            subject_alt_names: vec![ProtoSan {
                name: Some(Name::DnsName(leaf_name.to_string())),
            }],
            public_key,
            requestor: ACME_REQUESTOR.to_string(),
            metadata: Default::default(),
            csr_der,
            request_id: String::new(),
        }))
        .await
        .unwrap_or_else(|s| panic!("IssueCertificate failed: {:?}", s.code()))
        .into_inner();
    assert!(!issued.der_encoded.is_empty(), "issued certificate DER");

    // --- Revoke (Admin identity) ---
    let revoked = admin_rpc
        .revoke_certificate(Request::new(RevokeCertificateRequest {
            certificate_id: issued.certificate_id.clone(),
            reason: ProtoReason::KeyCompromise as i32,
            requestor: ADMIN_REQUESTOR.to_string(),
            justification: "grpc audit e2e".to_string(),
        }))
        .await
        .unwrap_or_else(|s| panic!("RevokeCertificate failed: {:?}", s.code()))
        .into_inner();
    assert!(revoked.success, "revocation succeeded");

    // --- GenerateCrl (Admin identity) ---
    let crl = admin_rpc
        .generate_crl(Request::new(GenerateCrlRequest {}))
        .await
        .unwrap_or_else(|s| panic!("GenerateCrl failed: {:?}", s.code()))
        .into_inner();
    assert!(crl.revoked_count >= 1, "CRL lists the revoked certificate");
    assert!(!crl.der_encoded.is_empty(), "CRL DER");

    let audit = AuditRepository::new(pool.clone());
    let crl_records = |events: &[AuditEvent]| {
        events
            .iter()
            .filter(|e| e.event_type == "crl_generation")
            .count()
    };
    let before = crl_records(&audit.all_events_ordered().await.expect("audit events"));

    // --- Negative (AC-3): an Issuer identity cannot reach GenerateCrl ---
    let denied = acme_rpc
        .generate_crl(Request::new(GenerateCrlRequest {}))
        .await
        .expect_err("Issuer GenerateCrl must be denied");
    assert!(
        denied.code() == Code::PermissionDenied,
        "Issuer GenerateCrl is PERMISSION_DENIED"
    );

    // --- Stored audit records ---
    let events = audit.all_events_ordered().await.expect("audit events");
    assert!(
        crl_records(&events) == before,
        "a denied GenerateCrl never reaches the handler"
    );
    let acme_serial = serial_hex(&acme_leaf.cert_pem);
    let admin_serial = serial_hex(&admin_leaf.cert_pem);

    // AU-2 / AC-3: the layer denial is stored as an `access_denied` Failure
    // record attributed to the denied peer (written before the response).
    let denials: Vec<&AuditEvent> = events
        .iter()
        .filter(|e| e.action == "access_denied")
        .collect();
    assert!(denials.len() == 1, "one stored access_denied record");
    let denial = denials[0];
    assert!(
        denial.event_type == "authorization" && denial.outcome == "failure",
        "access_denied: authorization Failure record"
    );
    assert!(
        denial.actor == ACME_SUBJECT,
        "access_denied: actor is the denied peer"
    );
    assert!(
        denial.target == GENERATE_CRL_PATH,
        "access_denied: target is the GenerateCrl method"
    );
    let denial_details = denial
        .details
        .as_ref()
        .unwrap_or_else(|| panic!("access_denied: details present"));
    assert!(
        denial_details["reason"] == "method_not_permitted",
        "access_denied: reason is method_not_permitted"
    );
    assert!(
        denial_details["listener"] == LISTENER,
        "access_denied: listener named"
    );
    assert!(
        denial_details["peer_serial"] == acme_serial.as_str(),
        "access_denied: peer_serial is the denied peer's serial"
    );

    let issuance = successes(&events, "certificate_issuance");
    assert!(issuance.len() == 1, "one successful issuance record");
    assert_peer_attributed(issuance[0], "issuance", ACME_SUBJECT, &acme_serial);
    assert!(
        issuance[0].details.as_ref().map(|d| &d["on_behalf_of"])
            == Some(&serde_json::json!(ACME_REQUESTOR)),
        "issuance: on_behalf_of is the bound requestor"
    );

    let revocation = successes(&events, "certificate_revocation");
    assert!(revocation.len() == 1, "one successful revocation record");
    assert_peer_attributed(revocation[0], "revocation", ADMIN_SUBJECT, &admin_serial);
    assert!(
        revocation[0].details.as_ref().map(|d| &d["on_behalf_of"])
            == Some(&serde_json::json!(ADMIN_REQUESTOR)),
        "revocation: on_behalf_of is the bound requestor"
    );

    // M13h kill: the GenerateCrl handler passes the verified admin peer.
    let generated: Vec<&AuditEvent> = successes(&events, "crl_generation")
        .into_iter()
        .filter(|e| e.action == "generate")
        .collect();
    assert!(generated.len() == 1, "one successful CRL generation record");
    assert_peer_attributed(generated[0], "crl_generation", ADMIN_SUBJECT, &admin_serial);
    assert!(
        generated[0].details.as_ref().map(|d| &d["crl_number"])
            == Some(&serde_json::json!(crl.crl_number)),
        "crl_generation: crl_number matches the response"
    );

    // --- AU-10: the stored chain, including the three signed gRPC-written
    // records above (and the unsigned access_denied record, covered by the
    // structural hash-chain check), verifies against the CA certificate's
    // SPKI. ---
    let sig_alg = Algorithm::EcdsaP256Sha256;
    let verifier = DatabaseAuditSink::new(pool.clone());
    assert!(
        verifier
            .verify_signed_chain(&ca_spki, sig_alg)
            .await
            .unwrap_or_else(|_| panic!("verify_signed_chain errored")),
        "signed audit chain verifies with the CA public key (AU-10)"
    );

    // A corrupted signature on the gRPC-written crl_generation record is
    // detected, so the verification above did cover that record.
    let mut bad_sig = generated[0]
        .signature
        .clone()
        .unwrap_or_else(|| panic!("crl_generation: signature present"));
    let first = bad_sig
        .first_mut()
        .unwrap_or_else(|| panic!("crl_generation: signature is not empty"));
    *first ^= 0xFF;
    sqlx::query("UPDATE audit_events SET signature = $1 WHERE id = $2")
        .bind(&bad_sig)
        .bind(generated[0].id)
        .execute(pool.pool())
        .await
        .unwrap_or_else(|_| panic!("corrupt crl_generation signature"));
    assert!(
        !verifier
            .verify_signed_chain(&ca_spki, sig_alg)
            .await
            .unwrap_or_else(|_| panic!("verify_signed_chain errored")),
        "a corrupted signature on the gRPC crl_generation record is detected (AU-10)"
    );

    // Best-effort cleanup (the temp dir is removed when `tmp` drops).
    for table in TABLES {
        let _ = sqlx::query(sqlx::AssertSqlSafe(format!("DELETE FROM {table}")))
            .execute(pool.pool())
            .await;
    }
}
